//! Rendering of `isa/*.toml` into Rust tables.

use crate::schema::Insn;

pub fn render(insns: &[Insn]) -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask codegen` from isa/*.toml; do not edit.\n");
    out.push_str("//\n// Regenerate with `cargo xtask codegen`.\n\n");
    out.push_str("use crate::{Format, Insn, Operand, OperandKind};\n\n");
    // rustfmt must not touch the table: the generator owns this file's layout,
    // and `codegen --check` compares bytes.
    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub static INSNS: &[Insn] = &[\n");
    for insn in insns {
        render_insn(&mut out, insn);
    }
    out.push_str("];\n");
    out
}

fn render_insn(out: &mut String, insn: &Insn) {
    out.push_str("    Insn {\n");
    out.push_str(&format!("        id: {:?},\n", insn.id));
    out.push_str(&format!("        mnemonic: {:?},\n", insn.mnemonic));
    out.push_str(&format!("        ext: {:?},\n", insn.ext));
    out.push_str(&format!(
        "        format: Format::{},\n",
        format_variant(&insn.format)
    ));
    let size = if insn.format.starts_with('C') { 2 } else { 4 };
    out.push_str(&format!("        size: {size},\n"));
    out.push_str(&format!("        opcode: 0b{:07b},\n", insn.opcode));
    out.push_str(&format!("        funct3: {},\n", opt_bits(insn.funct3, 3)));
    out.push_str(&format!("        funct7: {},\n", opt_bits(insn.funct7, 7)));
    out.push_str(&format!("        imm12: {},\n", opt_bits(insn.imm12, 12)));
    out.push_str(&format!("        class: {:?},\n", insn.class));
    if insn.operands.is_empty() {
        out.push_str("        operands: &[],\n");
    } else {
        out.push_str("        operands: &[\n");
        for operand in &insn.operands {
            out.push_str(&format!(
                "            Operand {{ kind: OperandKind::{}, bits: {}, signed: {}, align: {} }},\n",
                kind_variant(&operand.kind),
                operand.bits,
                operand.signed,
                operand.align
            ));
        }
        out.push_str("        ],\n");
    }
    out.push_str("    },\n");
}

fn opt_bits(value: Option<u32>, width: usize) -> String {
    match value {
        Some(bits) => format!("Some(0b{bits:0width$b})", width = width),
        None => "None".to_string(),
    }
}

fn format_variant(format: &str) -> &'static str {
    match format {
        "R" => "R",
        "I" => "I",
        "S" => "S",
        "B" => "B",
        "U" => "U",
        "J" => "J",
        "CI" => "Ci",
        "CR" => "Cr",
        "CSS" => "Css",
        "CIW" => "Ciw",
        "CL" => "Cl",
        "CS" => "Cs",
        "CA" => "Ca",
        "CB" => "Cb",
        "CJ" => "Cj",
        other => unreachable!("schema rejected format `{other}`"),
    }
}

fn kind_variant(kind: &str) -> &'static str {
    match kind {
        "rd" => "Rd",
        "rs1" => "Rs1",
        "rs2" => "Rs2",
        "imm" => "Imm",
        "shamt" => "Shamt",
        "csr" => "Csr",
        "zimm" => "Zimm",
        "pred" => "Pred",
        "succ" => "Succ",
        other => unreachable!("schema rejected operand kind `{other}`"),
    }
}
